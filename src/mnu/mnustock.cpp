// ──────────────────────────────────────────────────────────────────────
// One frame (processPad): open the window with system text 0x1b (step 0),
// load the textures (1, 2), set up the lists and the sprites (2), fade in
// with the button guides 4 and 5 (3), run the page (4), fade out (6, 7)
// and close (8). 1 when closed, -1 before open.
// ROR 0x0019a824

int MnuStock::exec(BedPad *pad)
{
    MagScene &scene = g_magSystem.m_scene;
    int ret = 0;

    if (m_open == 0)
        return -1;

    switch (m_step) {
    case 0:
        m_win = scene.openWindow(0x200, 0xe0, 0, -1);
        scene.updateWindowFont(m_win);
        g_magSystem.setViewParam(m_win, 0x90, 0x1a0, 0x8001, 0x200, 0xe0);
        scene.setWindowShow(m_win, 0);
        m_msg.setMessage(m_win, msgGetSysText(0x1b), 0);
        if (g_bss_7a3d4c != 0) {
            clearWork();
            g_bss_7a3d4c = 0;
        }
        m_step = 1;
        m_fade_wait = 0x1e;
        m_timer = 0;
        break;

    case 1:
        m_spr.m_tex.setList(mnuStockTexList, mnuStockRpk);
        m_step = 2;
        break;

    case 2:
        if (m_spr.m_tex.update() != 0) {
            m_step = 3;
            m_spr.m_font_in_pack = 1;
            m_spr.setFont(mnuStockFont, 0);
            m_spr.setFont(mnuStockFont, 1);
            setupLists(0);
            readMenuFlags();
            setDisp();
            ret = 0;
        }
        break;

    case 3:
        m_step = 4;
        for (int i = 0; i < MNUSTOCK_ROW_MAX; i++) {
            setRowName(m_row_spr[i], i);
            setRowCount(m_row_spr[i] + 9, i, i);
        }
        m_spr.fadeInSprite(MNUSTOCK_SPR_BAR, m_fade_wait, 10, 0, -1, g_sprColorClear, mnuStockColorFull);
        if (canScroll(0) == 0)
            m_spr.hideSprite(MNUSTOCK_SPR_UP);
        else
            m_spr.fadeInSprite(MNUSTOCK_SPR_UP, m_fade_wait, 10, 0, -1, g_sprColorClear, mnuStockColorFull);
        if (canScroll(1) == 0)
            m_spr.hideSprite(MNUSTOCK_SPR_DOWN);
        else
            m_spr.fadeInSprite(MNUSTOCK_SPR_DOWN, m_fade_wait, 10, 0, -1, g_sprColorClear, mnuStockColorFull);
        m_system = MagSystem::m_current_system;
        m_system->m_scene.fadeIn(0xf, 7, 0);
        scene.fadeInWindow(m_win, 0xf, 0, 0x80);
        g_gamMan.showMesSprite(5, 1, 0);
        g_gamMan.showMesSprite(4, 1, 0);
        g_gamMan.setMesSpritePos(5, 0x11c, 0x19a);
        g_gamMan.setMesSpritePos(4, 0x194, 0x19a);
        g_gamMan.fadeInMesSprite(5, 0xf);
        g_gamMan.fadeInMesSprite(4, 0xf);
        m_spr.saveVolume();
        SprMan::volumeOff();
        g_sndMan.playSe(5);
        ret = 0;
        break;

    case 4:
    {
        int r = 0;
        switch (m_page) {
        case 0: r = execPage0(pad); break;
        case 1: r = execPage1(pad); break;
        case 2: r = execPage2(pad); break;
        }
        if (r == 1)
            m_step = 6;
        update();
        ret = 0;
        break;
    }

    case 6:
        m_system->m_scene.fadeOut(0xf, 7, 0);
        scene.fadeOutWindow(m_win, 0xf, 0, 0x80);
        g_gamMan.fadeOutMesSprite(5, 0xf);
        g_gamMan.fadeOutMesSprite(4, 0xf);
        m_step = 7;
        break;

    case 7:
        ret = 0;
        if (m_system->m_scene.getFadeState() > 4) {
            g_sequence.m_global[0x15] = 6;
            m_spr.m_active = 0;
            scene.updateWindowFont(m_win);
            scene.closeWindow(m_win);
            g_gamMan.showMesSprite(5, 0, 0);
            g_gamMan.showMesSprite(4, 0, 0);
            m_step = 8;
        }
        break;

    case 5:
    case 8:
    default:
        g_sequence.m_bits[1] &= ~0x40000000u;
        m_spr.restoreVolume();
        m_step = 0;
        m_main_step = 0;
        ret = 1;
        break;
    }
    return ret;
}

