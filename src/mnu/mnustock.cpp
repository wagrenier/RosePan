// ──────────────────────────────────────────────────────────────────────
// The item's first icon pattern: 4 per icon from 0x6d (system data field
// 0xd, the icon number from 1), 0x6d when out of range; 0 for no item.
// ROR 0x0019af34

int MnuStock::getPatBase(int id)
{
    if (id == MNUSTOCK_ID_NONE || id == MNUSTOCK_ID_EMPTY)
        return 0;
    u_short icon[8];
    g_gamMan.m_sysData.getField(id & 0xffff, 0xd, icon);
    if (icon[0] != 0)
        icon[0]--;
    u_int pat = (u_int)icon[0] * 4 + 0x6d;
    if (pat > 0x24e)
        pat = 0x6d;
    return (int)pat;
}

// ──────────────────────────────────────────────────────────────────────
// ROR 0x0019afb0

int MnuStock::canScroll(int dir)
{
    if (m_count <= 7)
        return 0;
    if (dir == 0)
        return m_row != m_index;
    if (dir == 1)
        return m_count - 1 > m_index + (7 - m_row);
    return 0;
}

// ──────────────────────────────────────────────────────────────────────
// The list: entry 0 (the none entry), then the stock pool's items of the
// category (0 every one, 1..6 those whose record's m_b8 is it). The
// cursor and the window are kept inside it, then the scroll bar and the
// arrows follow.
// ROR 0x0019b020

void MnuStock::buildStockList(int category)
{
    SeqList<GamItemSlot> &used = g_gamMan.m_itemStock.m_used;
    int n = 1;

    memset(mnuStockNoneRec.m_head.m_name_jpn, '-', 16);
    mnuStockNoneRec.m_head.m_name_jpn[16] = '\0';
    strcpy(mnuStockNoneRec.m_head.m_name_eng, "Item Change");
    /* "アイテム欄からｽﾄｯｸへ移動する" (SJIS) */
    strcpy(mnuStockNoneRec.m_ba, "\x83\x41\x83\x43\x83\x65\x83\x80\x97\x93\x82\xa9\x82\xe7\xbd\xc4"
                                 "\xaf\xb8\x82\xd6\x88\xda\x93\xae\x82\xb7\x82\xe9");
    mnuStockNoneSlot.m_id = MNUSTOCK_ID_NONE;
    mnuStockNoneSlot.m_rec = &mnuStockNoneRec;
    mnuStockNoneSlot.m_oid = 0;
    m_list[0] = &mnuStockNoneSlot;

    for (SeqNode<GamItemSlot> *node = used.begin(); node != used.end(); node = node->m_next) {
        /* ROM: no bound on m_list (0x14e stock nodes, 0x100 entries). */
        m_list[n] = NULL;
        if (category == 0) {
            m_list[n++] = &node->m_data;
        } else if (category >= 0 && category < 7
                   && category == ((const GamSysRec5 *)node->m_data.m_rec)->m_b8) {
            m_list[n++] = &node->m_data;
        }
    }

    m_list_num = n;
    m_count = n;
    if (m_row >= m_rows)
        m_row = 0;
    if (m_index - m_row < 0)
        m_index = m_row;
    if (m_rows < m_count) {
        if ((m_index - m_row) + m_rows - 1 >= m_count)
            m_index = m_count + (m_row - m_rows);
    } else {
        m_index = m_row;
        if (m_row >= m_count) {
            m_row = m_count - 1;
            m_index = m_count - 1;
        }
    }

    sprite(MNUSTOCK_SPR_BAR).m_off[1] = getScrollBarPos(m_index, m_count) << 4;
    if (canScroll(0) == 0) {
        if (sprite(MNUSTOCK_SPR_UP).m_state != 0)
            m_spr.fadeOutDefault(MNUSTOCK_SPR_UP, 10);
    } else if (sprite(MNUSTOCK_SPR_UP).m_state != 1) {
        m_spr.fadeInSprite(MNUSTOCK_SPR_UP, m_fade_wait, 10, 0, -1, g_sprColorClear, mnuStockColorFull);
    }
    if (canScroll(1) == 0) {
        if (sprite(MNUSTOCK_SPR_DOWN).m_state != 0)
            m_spr.fadeOutDefault(MNUSTOCK_SPR_DOWN, 10);
    } else if (sprite(MNUSTOCK_SPR_DOWN).m_state != 1) {
        m_spr.fadeInSprite(MNUSTOCK_SPR_DOWN, m_fade_wait, 10, 0, -1, g_sprColorClear, mnuStockColorFull);
    }
}

