// ──────────────────────────────────────────────────────────────────────
// The menu flags from sequence bit-word 1 (MnuItem::readMenuFlags' code
// without its slot-7 rule): bit 0 m_flag_b / d, bit 1 m_flag_a / c, bit
// 2 m_flag_bit2.
// ROR 0x0019ae78

void MnuStock::readMenuFlags()
{
    if ((g_sequence.m_bits[1] & 1) == 1) {
        m_flag_b = 1;
        m_flag_d = 1;
    } else {
        m_flag_d = 0;
        m_flag_b = 0;
    }
    if ((g_sequence.m_bits[1] & 2) == 0) {
        m_flag_c = 0;
        m_flag_a = 0;
    } else {
        m_flag_a = 1;
        m_flag_c = 1;
    }
    m_flag_bit2 = (g_sequence.m_bits[1] & 4) != 0;
}

