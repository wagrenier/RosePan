// ──────────────────────────────────────────────────────────────────────
// One frame (processPad): open the window and hide the scene's message
// sprites (step 0), start the card work and the display list (1..3, fade
// in), run the sub screen (4), fade out (6, 7) and close (8: m_global
// 0x15 = 7 after a save, 8 after a load). 1 when closed, -1 before open.
// ROR 0x001a5ed0

int MnuSvld::exec(BedPad *pad)
{
    MagScene &scene = g_magSystem.m_scene;
    int ret = 0;
    int r;

    if (m_open == 0)
        return -1;

    switch (m_step) {
    case 0:
        m_win_shown = 0;
        m_accessed = 0;
        m_win = scene.openWindow(0x200, 0xe0, 0, -1);
        scene.updateWindowFont(m_win);
        g_magSystem.setViewParam(m_win, 0x88, 0x1a0, 0x8001, 0x200, 0xe0);
        scene.setWindowShow(m_win, 1);
        m_msg.setMessage(m_win, msgGetSysText(0x19), 0);
        clearSlots();
        for (int i = 0; i < 14; i++)
            scene.m_mes.backupSprite(mnuSvldMesSprite[i]);
        for (int i = 0; i < 14; i++)
            scene.m_mes.setSpriteProcessOn(mnuSvldMesSprite[i]);
        m_step = 1;
        setSlotsDisp();
        /* fall through */
    case 1:
        m_step = 2;
        m_mcd.init(NULL);
        if (m_save == 0)
            m_mcd.setTextMode(2);
        else if (m_save == 1)
            m_mcd.setTextMode(1);
        /* fall through */
    case 2:
        m_step = 3;
        setDisp();
        g_gamMan.showMesSprite(5, 0, 0);
        g_gamMan.showMesSprite(4, 0, 0);
        g_gamMan.setMesSpritePos(5, 0x11c, 0x19a);
        g_gamMan.setMesSpritePos(4, 0x194, 0x19a);
        /* fall through */
    case 3:
        setSlotsDisp();
        m_step = 4;
        m_24f4 = 1;
        m_system = MagSystem::m_current_system;
        m_system->m_scene.fadeIn(0xf, 7, 0);
        m_spr.saveVolume();
        SprMan::volumeOff();
        g_sndMan.playSe(5);
        return 0;

    case 4:
        switch (m_sub) {
        case 0:
            r = execList(pad);
            if (r == 2 || r == 3)
                m_sub = r;
            else if (r == 1)
                m_sub = 1;
            else if (r == 999)
                m_step = 6;
            break;
        case 1:
            if (execCheck(pad) == 999)
                m_step = 6;
            break;
        case 2:
            r = execSave(pad);
            if (r == 1)
                m_sub = 1;
            else if (r == 999)
                m_step = 6;
            break;
        case 3:
            r = execLoad(pad);
            if (r == 1)
                m_sub = 1;
            else if (r == 999)
                m_step = 6;
            break;
        default:
            m_step = 6;
            break;
        }
        m_mcd.processPad(pad);
        update();
        ret = 0;
        break;

    case 6:
        m_system->m_scene.fadeOut(0xf, 7, 0);
        if (m_win_shown != 0) {
            scene.fadeOutWindow(m_win, 0xf, 0, 0x80);
            g_gamMan.fadeOutMesSprite(5, 0xf);
            g_gamMan.fadeOutMesSprite(4, 0xf);
        }
        m_step = 7;
        break;

    case 7:
        if (m_system->m_scene.getFadeState() < 5) {
            ret = 0;
        } else {
            m_spr.m_active = 0;
            m_mcd.term();
            m_step = 8;
        }
        break;

    default:    /* 5, 8 */
        g_sequence.m_global[0x15] = m_save == 1 ? 7 : 8;
        ret = 1;
        g_sequence.m_bits[1] &= ~0x40000000u;
        m_spr.restoreVolume();
        m_step = 0;
        m_sub_step = 0;
        scene.updateWindowFont(m_win);
        scene.closeWindow(m_win);
        g_gamMan.showMesSprite(5, 0, 0);
        g_gamMan.showMesSprite(4, 0, 0);
        for (int i = 0; i < 14; i++)
            scene.m_mes.restoreSprite(mnuSvldMesSprite[i]);
        break;
    }
    return ret;
}

