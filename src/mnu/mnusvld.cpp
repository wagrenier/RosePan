// ──────────────────────────────────────────────────────────────────────
// The file for the game being saved: chapter 1..13 -> 0..12, the play
// time (99:59 at most), and the flag from sequence bit 0x80000000 of word
// 0; all zero while bit 0x1000 of word 8 is set.
// ROR 0x001a6968

void MnuSvld::makeSaveName(int slot, char *buf)
{
    int minutes = 0;
    int chapter = 0;
    int flag;

    g_gamMan.getStatus(4, &chapter);
    flag = 1;
    g_gamMan.getStatus(3, &minutes);
    int hour = minutes / 60;
    int minute = minutes % 60;
    chapter = chapter - 1;
    if (chapter < 0)
        chapter = 0;
    if (chapter > 12)
        chapter = 12;
    if (minutes < 5999) {
        if (hour >= 100)
            hour = 99;
        if (hour < 0)
            hour = 0;
        if (minute < 0)
            minute = 0;
        if (minute >= 60)
            minute = 59;
    } else {
        hour = 99;
        minute = 59;
    }
    if ((g_sequence.m_bits[8] & 0x1000) != 0) {
        chapter = 0;
        hour = 0;
        minute = 0;
    } else {
        flag = (int)g_sequence.m_bits[0] < 0;
    }
    sprintf(buf, "%s/%s%02d%d%d%02d%02d%02d", mnuSvldCardDir, mnuSvldPrefix, slot, 0, flag,
            chapter, hour, minute);
}

// ──────────────────────────────────────────────────────────────────────
// The slot's directory: a new name with the slot number, or the name of
// the card's existing dt<slot> directory.
// ROR 0x001a6ab8

void MnuSvld::makeSaveDir(int slot, char *buf)
{
    char tens = (char)(slot / 10 + '0');
    char ones = (char)(slot % 10 + '0');

    buf[0] = 0;
    sprintf(buf, "%s/%s%d%d________", mnuSvldCardDir, mnuSvldPrefix, slot / 10, slot % 10);
    if (m_mcd.getFileNum() <= 0)
        return;
    for (int i = 0; i < m_mcd.getFileNum(); i++) {
        const char *name = m_mcd.m_mcd.getDirName(i);
        if (name[0] == 'd' && name[1] == 't' && name[2] == tens && name[3] == ones) {
            buf[0] = 0;
            sprintf(buf, "%s/%s", mnuSvldCardDir, name);
            return;
        }
    }
}

