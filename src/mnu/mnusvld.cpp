// ──────────────────────────────────────────────────────────────────────
// Row row of the list shows slot slot: its chapter picture (sprite 29 +
// row, pattern 10 + chapter; hidden with the info texts when the slot is
// empty) and its play time (sprite 41 + row: "hh:mm", "--:--" when none).
// ROR 0x001a6c90

void MnuSvld::setSlotDisp(int row, int slot)
{
    sprite(row + 0x29).m_clear_rect = mnuSvldRectTime;
    if (slot >= MNUSVLD_SLOT_MAX)
        return;

    MnuSvldSlot &s = m_slot[slot];
    int no = row + 0x1d;
    if ((u_int)s.m_chapter < 13) {
        sprite(no).m_pat_base = s.m_chapter + 10;
        sprite(no).m_state = 1;
        m_spr.setAnim(no, 0);
        sprite(no).m_disp = 1;
    } else {
        sprite(no).m_pat_base = 10;
        m_spr.setAnim(no, 0);
        sprite(no).m_disp = 0;
        sprite(no).m_state = 0;
        sprite(0x42).m_state = 0;
        sprite(0x40).m_state = 0;
        sprite(0x41).m_state = 0;
        sprite(0x43).m_state = 0;
    }

    char *t = mnuSvldTime[row];
    if (s.m_hour < 0) {
        strcpy(t, "--:--");
    } else {
        if (s.m_hour < 100) {
            t[0] = (char)(s.m_hour / 10 + '0');
            t[1] = (char)(s.m_hour % 10 + '0');
        } else {
            t[0] = '9';
            t[1] = '9';
        }
        t[2] = ':';
        if (s.m_minute < 60) {
            t[3] = (char)(s.m_minute / 10 + '0');
            t[4] = (char)(s.m_minute % 10 + '0');
        } else {
            t[3] = '5';
            t[4] = '9';
        }
        t[5] = 0;
    }
    sprite(row + 0x29).m_text_x = 0;
    sprite(row + 0x29).m_text_y = 0;
    sprite(row + 0x29).m_text = t;
}

