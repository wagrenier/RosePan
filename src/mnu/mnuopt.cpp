// ──────────────────────────────────────────────────────────────────────
// Fades everything in after 0x32 frames over 0x14: the frame, the
// cursor on rows 0 / 5, every value dim, then each row's chosen value
// full (anim 1 on the cursor's row).
// ROR 0x001abb58

void MnuOpt::fadeInItems()
{
    static const int frame[10] = { 0xe, 0x13, 0xf, 0x10, 0x11, 0x12, 0x14, 0x3d, 0x3e, 0x3f };
    int sel[8];

    for (int i = 7; i >= 0; i--)
        sel[i] = 0;
    for (int i = 0; i < 10; i++)
        m_spr.fadeInSprite(frame[i], 0x32, 0x14, 0, -1, g_sprColorClear,
                           frame[i] == 0x3f ? mnuOptColorDim : mnuOptColorFull);

    int row = m_cursor;
    if (row == 0 || row == 5) {
        int v = row * 2 + m_value[row];
        sprite(MNUOPT_CURSOR_SPRITE).m_off[0] = mnuOptCursorPos[v][0];
        sprite(MNUOPT_CURSOR_SPRITE).m_off[1] = mnuOptCursorPos[v][1];
    }
    if (row >= 1 && row <= 4)
        sprite(MNUOPT_CURSOR_SPRITE).m_state = 0;
    else if (row == 0 || row == 5)
        m_spr.fadeInSprite(MNUOPT_CURSOR_SPRITE, 0x32, 0x14, 0, -1, g_sprColorClear, mnuOptColorFull);

    m_spr.fadeInWait(4, 0x32, 0x14, g_sprColorClear, mnuOptColorDim);
    for (int n = 0x15; n <= 0x18; n++)
        m_spr.fadeInSprite(n, 0x32, 0x14, 0, -1, g_sprColorClear, mnuOptColorDim);
    for (int n = 0x22; n <= 0x2a; n++)
        m_spr.fadeInSprite(n, 0x32, 0x14, 0, -1, g_sprColorClear, mnuOptColorDim);
    for (int n = 0x19; n <= 0x3c; n++)
        if (n < 0x22 || n > 0x2a)
            m_spr.fadeInSprite(n, 0x32, 0x14, 0, -1, g_sprColorClear, mnuOptColorDim);

    sel[m_cursor] = 1;
    if (m_value[0] == 0)
        m_spr.fadeInSprite(0x15, 0x32, 0x14, sel[0], -1, g_sprColorClear, mnuOptColorFull);
    else if (m_value[0] == 1)
        m_spr.fadeInSprite(0x16, 0x32, 0x14, sel[0], -1, g_sprColorClear, mnuOptColorFull);
    if (m_value[5] == 0)
        m_spr.fadeInSprite(0x17, 0x32, 0x14, sel[5], -1, g_sprColorClear, mnuOptColorFull);
    else if (m_value[5] == 1)
        m_spr.fadeInSprite(0x18, 0x32, 0x14, sel[5], -1, g_sprColorClear, mnuOptColorFull);
    for (int r = 1; r <= 4; r++)
        m_spr.fadeInSprite(mnuOptLevelSprite[r] + m_value[r], 0x32, 0x14, sel[r], -1,
                           g_sprColorClear, mnuOptColorFull);
}

// ──────────────────────────────────────────────────────────────────────
// The options' input. Step 0 reads GamMan's option block into m_value
// and fades in, 1 waits 0x47 frames, then every frame (3): up / down
// move the row, left / right change its value (GamMan's field follows;
// brightness and master volume call setOption at once, the others when
// the row is redrawn), triangle leaves (4: returns 1). Any direction
// sets GamMan m_flags2 0x400, which makes triangle set every option
// again. A change redraws: the old row's anims off, the new row's
// chosen value full and the others dim, the cursor sprite on rows 0 / 5.
// Sound is on only while the master volume row is chosen.
// ROR 0x001ac5b0

int MnuOpt::execMain(BedPad *pad)
{
    u_int changed = 0;

    switch (m_main_step) {
    case 0:
        g_gamMan.getStatus(0x15, &m_values);
        m_10d4 = -1;
        m_main_step = 1;
        m_vib_time = 0;
        m_vib_off = 0;
        m_result = 0;
        m_value[0] = m_values->m_output;
        m_value[1] = m_values->m_str;
        m_value[2] = m_values->m_se;
        m_value[3] = m_values->m_bright;
        m_value[4] = m_values->m_master;
        m_value[5] = m_values->m_vibration == 0;
        fadeInItems();
        m_timer = 0;
        /* fall through */
    case 1:
        if (m_timer++ < 0x47)
            return 0;
        m_main_step = 3;
        break;
    case 4:
        if (m_result == 1)
            return 1;
        if (m_system->m_scene.getFadeState() < 5)
            return 0;
        return m_result;
    default:
        break;
    }

    int prev = m_cursor;

    if ((pad->m_dir_repeat & 0x10) != 0) {
        g_gamMan.m_flags2 |= 0x400;
        if (m_cursor > 0) {
            changed = 1;
            g_sndMan.playSe(1);
            m_cursor--;
        }
    }
    if ((pad->m_dir_repeat & 0x40) != 0) {
        g_gamMan.m_flags2 |= 0x400;
        if (m_cursor < m_cursor_num[0] - 1) {
            changed = 1;
            g_sndMan.playSe(1);
            m_cursor++;
        }
    }

    if ((pad->m_dir_repeat & 0x80) != 0) {
        g_gamMan.m_flags2 |= 0x400;
        switch (m_cursor) {
        case 0:
            if (m_value[0] == 1) {
                m_value[0] = 0;
                changed |= 2;
                m_values->m_output = 0;
                g_sndMan.playSe(1);
            }
            break;
        case 1:
        case 2:
        case 3:
        case 4:
            if (m_value[m_cursor] > 0) {
                int *level = mnuOptLevel(m_values, m_cursor);
                m_value[m_cursor]--;
                changed |= 2;
                (*level)--;
                if (m_cursor >= 3)
                    g_gamMan.setOption(mnuOptLevelOption[m_cursor], *level);
                g_sndMan.playSe(1);
            }
            break;
        case 5:
            if (m_value[5] == 1) {
                m_value[5] = 0;
                changed |= 2;
                m_values->m_vibration = 0;
                g_sndMan.playSe(1);
            }
            break;
        }
    }

    if ((pad->m_dir_repeat & 0x20) != 0) {
        g_gamMan.m_flags2 |= 0x400;
        switch (m_cursor) {
        case 0:
            if (m_value[0] == 0) {
                m_value[0] = 1;
                changed |= 2;
                m_values->m_output = 1;
                g_sndMan.playSe(1);
            }
            break;
        case 1:
        case 2:
        case 3:
        case 4:
            if (m_value[m_cursor] < 8) {
                int *level = mnuOptLevel(m_values, m_cursor);
                m_value[m_cursor]++;
                changed |= 2;
                (*level)++;
                if (m_cursor >= 3)
                    g_gamMan.setOption(mnuOptLevelOption[m_cursor], *level);
                g_sndMan.playSe(1);
            }
            break;
        case 5:
            if (m_value[5] == 0) {
                m_value[5] = 1;
                changed |= 2;
                m_values->m_vibration = 1;
                g_sndMan.playSe(1);
            }
            break;
        }
    }

    if ((pad->m_trig & 0x2000) != 0) {
        if ((g_gamMan.m_flags2 & 0x400) != 0) {
            g_gamMan.setOption(2, m_values->m_str);
            g_gamMan.setOption(3, m_values->m_se);
            g_gamMan.setOption(0, m_values->m_bright);
            g_gamMan.setOption(1, m_values->m_master);
            g_gamMan.setOption(7, m_values->m_vibration);
        }
        g_sndMan.playSe(2);
        m_result = 1;
        m_main_step = 4;
        SprMan::volumeOff();
    }

    if (changed == 0)
        return 0;

    /* The row was left: its anims off. */
    if ((changed & 1) != 0) {
        switch (prev) {
        case 0:
            m_spr.setAnim(0x15, 0);
            sprite(0x15).m_disp = 1;
            m_spr.setAnim(0x16, 0);
            sprite(0x16).m_disp = 1;
            break;
        case 1:
        case 2:
        case 3:
        case 4:
            for (int i = 0; i < 9; i++) {
                m_spr.setAnim(mnuOptLevelSprite[prev] + i, 0);
                sprite(mnuOptLevelSprite[prev] + i).m_disp = 1;
            }
            break;
        case 5:
            m_spr.setAnim(0x17, 0);
            sprite(0x17).m_disp = 1;
            m_spr.setAnim(0x18, 0);
            sprite(0x18).m_disp = 1;
            break;
        }
        changed |= 2;
        if (m_cursor == 4)
            SprMan::volumeOn();
        else
            SprMan::volumeOff();
    }

    if ((changed & 2) == 0)
        return 0;

    /* The cursor sprite on the two-choice rows. */
    int row = m_cursor;
    if (row == 0 || row == 5) {
        int v = row * 2 + m_value[row];
        sprite(MNUOPT_CURSOR_SPRITE).m_off[0] = mnuOptCursorPos[v][0];
        sprite(MNUOPT_CURSOR_SPRITE).m_off[1] = mnuOptCursorPos[v][1];
    }
    if (row >= 1 && row <= 4) {
        sprite(MNUOPT_CURSOR_SPRITE).m_state = 0;
    } else if (row == 0 || row == 5) {
        sprite(MNUOPT_CURSOR_SPRITE).m_state = 1;
        m_spr.setAnim(MNUOPT_CURSOR_SPRITE, 1);
        sprite(MNUOPT_CURSOR_SPRITE).m_disp = 1;
    }

    /* The row's values: the chosen one full, the others dim. */
    switch (m_cursor) {
    case 0:
        if (m_value[0] == 0) {
            m_spr.setAnim(0x15, 1);
            sprite(0x15).m_disp = 1;
            m_spr.setAnim(0x16, 0);
            sprite(0x16).m_disp = 1;
            setColor(0x15, 0x80, 0x80, 0x80, 0x80);
            setColor(0x16, 0x80, 0x80, 0x80, 0x28);
        } else if (m_value[0] == 1) {
            m_spr.setAnim(0x15, 0);
            sprite(0x15).m_disp = 1;
            m_spr.setAnim(0x16, 1);
            sprite(0x16).m_disp = 1;
            setColor(0x15, 0x80, 0x80, 0x80, 0x28);
            setColor(0x16, 0x80, 0x80, 0x80, 0x80);
        }
        g_gamMan.setOption(6, m_values->m_output);
        break;

    case 1:
    case 2:
    case 3:
    case 4:
    {
        int base = mnuOptLevelSprite[m_cursor];
        for (int i = 0; i < 9; i++) {
            m_spr.setAnim(base + i, 0);
            sprite(base + i).m_disp = 1;
            setColor(base + i, 0x80, 0x80, 0x80, 0x28);
        }
        int n = base + m_value[m_cursor];
        m_spr.setAnim(n, 1);
        sprite(n).m_disp = 1;
        setColor(n, 0x80, 0x80, 0x80, 0x80);
        if (m_cursor <= 2)
            g_gamMan.setOption(mnuOptLevelOption[m_cursor], *mnuOptLevel(m_values, m_cursor));
        break;
    }

    case 5:
        if (m_value[5] == 0) {
            m_spr.setAnim(0x17, 1);
            sprite(0x17).m_disp = 1;
            m_spr.setAnim(0x18, 0);
            sprite(0x18).m_disp = 1;
            setColor(0x17, 0x80, 0x80, 0x80, 0x80);
            setColor(0x18, 0x80, 0x80, 0x80, 0x28);
            m_vib_time = 0xf;
            g_gamMan.setOption(7, 1);
            if (m_vib_off != 0) {
                /* ROM: m_vib_off stays set, so every redraw of this row
                 * with vibration on pulses the pad again. */
                m_system->m_vib_on = 1;
                m_system->startVibration(0xf);
                return 0;
            }
            m_vib_off = 0;
        } else if (m_value[5] == 1) {
            m_spr.setAnim(0x17, 0);
            sprite(0x17).m_disp = 1;
            m_spr.setAnim(0x18, 1);
            sprite(0x18).m_disp = 1;
            setColor(0x17, 0x80, 0x80, 0x80, 0x28);
            setColor(0x18, 0x80, 0x80, 0x80, 0x80);
            m_vib_time = 0;
            g_gamMan.setOption(7, 0);
            m_system->m_vib_on = 0;
            m_vib_off = 1;
        }
        break;
    }
    return 0;
}
