// ──────────────────────────────────────────────────────────────────────
// One frame (processPad): open the window with system text 0x1c (step 0),
// load the textures (1, 2), set up the sprites and fade in with the
// button guide 4 (3), run execMain (4), fade out (6, 7) and close (8). 1
// when closed, -1 before open.
// ROR 0x001ab720

int MnuOpt::exec(BedPad *pad)
{
    MagScene &scene = g_magSystem.m_scene;
    int ret = 0;

    if (m_open == 0)
        return -1;

    switch (m_step) {
    case 0:
        m_win = scene.openWindow(0x200, 0xe0, 0, -1);
        scene.updateWindowFont(m_win);
        g_magSystem.setViewParam(m_win, 0xc0, 0x1a0, 0x8001, 0x200, 0xe0);
        scene.setWindowShow(m_win, 0);
        m_msg.setMessage(m_win, msgGetSysText(0x1c), 0);
        m_step = 1;
        /* fall through */
    case 1:
        m_spr.m_tex.setList(mnuOptTexList, mnuOptRpk);
        m_step = 2;
        break;

    case 2:
        if (m_spr.m_tex.update() != 0)
            m_step = 3;
        break;

    case 3:
        m_step = 4;
        setDisp();
        m_system->m_scene.fadeIn(0xf, 7, 0);
        scene.fadeInWindow(m_win, 0xf, 0, 0x80);
        g_gamMan.showMesSprite(4, 1, 0);
        g_gamMan.setMesSpritePos(4, 0x1a8, 0x19a);
        g_gamMan.fadeInMesSprite(4, 0xf);
        m_spr.saveVolume();
        SprMan::volumeOff();
        /* fall through */
    case 4:
        if (m_pause == 0 && execMain(pad) == 1)
            m_step = 6;
        update();
        ret = 0;
        break;

    case 5:
    case 8:
        m_step = 0;
        m_main_step = 0;
        ret = 1;
        m_spr.restoreVolume();
        break;

    case 6:
        m_system->m_scene.fadeOut(0xf, 7, 0);
        scene.fadeOutWindow(m_win, 0xf, 0, 0x80);
        g_gamMan.fadeOutMesSprite(4, 0xf);
        m_step = 7;
        /* fall through */
    case 7:
        if (m_system->m_scene.getFadeState() < 5) {
            ret = 0;
        } else {
            m_spr.m_active = 0;
            scene.updateWindowFont(m_win);
            scene.closeWindow(m_win);
            g_gamMan.showMesSprite(4, 0, 0);
            m_step = 8;
        }
        break;

    default:
        m_step = 0;
        m_main_step = 0;
        ret = 1;
        m_spr.restoreVolume();
        break;
    }
    return ret;
}

